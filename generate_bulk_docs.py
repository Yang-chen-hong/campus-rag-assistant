# ==================== 策略1: 段落拆分 ====================
def split_paragraphs(docs: List[Dict]) -> List[Dict]:
    """将每篇文档按双换行拆分成细粒度段落"""
    chunks = []
    for doc in docs:
        title = doc.get("title", "")
        content = doc.get("content", "")
        paragraphs = [p.strip() for p in content.split("\n\n") if p.strip() and len(p.strip()) > 20]

        if len(paragraphs) <= 1:
            chunks.append(doc)
            continue

        for i, para in enumerate(paragraphs):
            # 跳过纯标题行（如"一、学费标准"）
            if len(para) < 30 and not any(c in para for c in "：;。；"):
                continue
            chunks.append({
                "title": f"{title}（第{i+1}段）",
                "content": f"{title} - 第{i+1}段\n\n{para}",
            })

    return chunks


