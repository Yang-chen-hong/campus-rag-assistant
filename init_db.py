def init_database():
    """检查并添加结构化政策文档到数据库"""
    try:
        client = chromadb.PersistentClient(path=DB_PATH)
        col = client.get_or_create_collection(
            name=COLLECTION_NAME,
            metadata={"hnsw:space": "cosine"}
        )

        # 检查是否已经有政策文档
        existing = col.get(where={"source": "structured_policy"}, include=["metadatas"])
        existing_count = len(existing.get("ids", []))

        if existing_count >= len(POLICY_DOCS):
            return  # 已经初始化过了

        # 需要添加的文档
        from zhipu_api import create_embedding

        added = 0
        for i, doc in enumerate(POLICY_DOCS):
            doc_id = f"policy_struct_{i}"
            # 检查是否已存在
            existing_doc = col.get(ids=[doc_id])
            if existing_doc and existing_doc.get("ids"):
                continue  # 已存在，跳过

            try:
                embedding = create_embedding(doc["content"])
                col.add(
                    ids=[doc_id],
                    documents=[doc["content"]],
                    embeddings=[embedding],
                    metadatas=[{"title": doc["title"], "source": "structured_policy"}]
                )
                added += 1
            except Exception:
                pass  # embedding 失败就跳过

    except Exception:
        pass  # 数据库初始化失败不影响应用启动
