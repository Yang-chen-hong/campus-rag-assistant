def add_to_database(docs):
    from retriever import get_embedding, get_chroma_collection

    collection = get_chroma_collection()
    existing = collection.count()
    print(f"数据库现有: {existing} 条")

    batch_size = 500
    total_added = 0

    for i in range(0, len(docs), batch_size):
        batch = docs[i:i + batch_size]
        ids = [f"extra_{existing + i + j}" for j in range(len(batch))]
        texts = [d["content"] for d in batch]
        embeddings = [get_embedding(text) for text in texts]
        metadatas = [{"title": d["title"]} for d in batch]
        collection.upsert(ids=ids, documents=texts, embeddings=embeddings, metadatas=metadatas)
        total_added += len(batch)
        print(f"  已添加 {total_added}/{len(docs)}")

    final_count = collection.count()
    print(f"\n数据库最终: {final_count} 条")


